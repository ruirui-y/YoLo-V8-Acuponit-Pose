def depth_structure_view(depth: np.ndarray) -> np.ndarray:
    """Normalize valid pixels to 1..255 for visualization only, preserving invalid=0."""
    out = np.zeros_like(depth, dtype=np.uint8)
    valid = depth > 0
    if not np.any(valid):
        return out
    values = depth[valid].astype(np.float32)
    lo = float(values.min())
    hi = float(values.max())
    if hi <= lo:
        out[valid] = 180
    else:
        scaled = 1.0 + (values - lo) * (254.0 / (hi - lo))
        out[valid] = np.clip(np.rint(scaled), 1, 255).astype(np.uint8)
    return out


def draw_box(ax, box: np.ndarray | None, edgecolor: str, linewidth: float, linestyle: str = "-") -> None:
    if box is None:
        return
    x1, y1, x2, y2 = [float(v) for v in box]
    ax.add_patch(
        Rectangle(
            (x1, y1),
            max(0.0, x2 - x1),
            max(0.0, y2 - y1),
            fill=False,
            edgecolor=edgecolor,
            linewidth=linewidth,
            linestyle=linestyle,
        )
    )


def draw_prediction_overlay(
    ax,
    rgb: np.ndarray,
    gt: dict[str, Any] | None,
    pred: dict[str, Any] | None,
    true_errors: np.ndarray | None,
) -> tuple[float | None, float | None]:
    ax.imshow(rgb)
    mean_err: float | None = None
    delta_err: float | None = None

    if gt is not None:
        draw_box(ax, gt["box"], "white", 1.6, "--")
        gt_kpts = np.asarray(gt["keypoints"])
        for idx, (x, y, visibility) in enumerate(gt_kpts):
            if visibility <= 0:
                continue
            ax.scatter([x], [y], s=30, marker="o", c="magenta", edgecolors="white", linewidths=0.6)
            ax.text(x + 4, y + 4, f"K{idx}", color="white", fontsize=7, weight="bold")

    if pred is not None and pred.get("box") is not None:
        draw_box(ax, pred["box"], "lime", 1.6)
        pred_kpts = pred.get("keypoints")
        if pred_kpts is not None:
            pred_kpts = np.asarray(pred_kpts)
            for idx, (x, y, _conf) in enumerate(pred_kpts):
                ax.scatter([x], [y], s=34, marker="x", c="cyan", linewidths=1.5)
                if gt is not None and idx < len(gt["keypoints"]) and gt["keypoints"][idx, 2] > 0:
                    gx, gy = gt["keypoints"][idx, :2]
                    ax.plot([gx, x], [gy, y], color="yellow", linewidth=0.8, alpha=0.9)

    if pred is not None:
        errs = keypoint_errors(gt, pred)
        if errs is not None and np.any(np.isfinite(errs)):
            mean_err = float(np.nanmean(errs))
            if true_errors is not None and np.any(np.isfinite(true_errors)):
                delta_err = mean_err - float(np.nanmean(true_errors))

    ax.set_axis_off()
    return mean_err, delta_err


def safe_title(text: str, limit: int = 30) -> str:
    return text if len(text) <= limit else text[: limit - 1] + "…"


def plot_group_figure(
    output_path: Path,
    image_name: str,
    group_name: str,
    variants: list[str],
    images: dict[str, np.ndarray],
    gt: dict[str, Any] | None,
    predictions: dict[str, dict[str, Any] | None],
) -> None:
    ncols = len(variants)
    if ncols == 0:
        return

    true_depth = images["true_depth"][:, :, 3] if "true_depth" in images else images[variants[0]][:, :, 3]
    true_errors = None
    true_pred = predictions.get("true_depth")
    if true_pred is not None:
        true_errors = keypoint_errors(gt, true_pred)

    fig, axes = plt.subplots(4, ncols, figsize=(max(11.0, 3.15 * ncols), 11.2), squeeze=False)
    for col, variant in enumerate(variants):
        image = images[variant]
        rgb = cv2.cvtColor(image[:, :, :3], cv2.COLOR_BGR2RGB)
        depth = image[:, :, 3]
        diff = np.abs(depth.astype(np.int16) - true_depth.astype(np.int16)).astype(np.uint8)

        ax = axes[0, col]
        im = ax.imshow(depth, cmap="turbo", vmin=0, vmax=255)
        ax.set_title(safe_title(VARIANT_LABELS.get(variant, variant)), fontsize=9, weight="bold")
        ax.set_axis_off()
        valid = depth > 0
        valid_mean = float(depth[valid].mean()) if np.any(valid) else 0.0
        ax.text(
            0.02,
            0.02,
            f"mean(valid)={valid_mean:.1f}\nmin={int(depth.min())} max={int(depth.max())}",
            transform=ax.transAxes,
            fontsize=7,
            color="white",
            va="bottom",
            bbox=dict(facecolor="black", alpha=0.55, pad=2),
        )
        if col == ncols - 1:
            fig.colorbar(im, ax=ax, fraction=0.046, pad=0.02, label="Depth 0..255")

        ax = axes[1, col]
        ax.imshow(depth_structure_view(depth), cmap="turbo", vmin=0, vmax=255)
        ax.set_axis_off()
        ax.text(
            0.02,
            0.02,
            "VIS ONLY: valid min-max normalized",
            transform=ax.transAxes,
            fontsize=7,
            color="white",
            va="bottom",
            bbox=dict(facecolor="black", alpha=0.55, pad=2),
        )

        ax = axes[2, col]
        diff_im = ax.imshow(diff, cmap="magma", vmin=0, vmax=255)
        ax.set_axis_off()
        if np.any(true_depth > 0):
            mae_valid = float(
                np.mean(
                    np.abs(depth.astype(np.float32) - true_depth.astype(np.float32))[true_depth > 0]
                )
            )
        else:
            mae_valid = 0.0
        ax.text(
            0.02,
            0.02,
            f"|variant-true|\nMAE(valid)={mae_valid:.2f}",
            transform=ax.transAxes,
            fontsize=7,
            color="white",
            va="bottom",
            bbox=dict(facecolor="black", alpha=0.55, pad=2),
        )
        if col == ncols - 1:
            fig.colorbar(diff_im, ax=ax, fraction=0.046, pad=0.02, label="Absolute difference")

        ax = axes[3, col]
        mean_err, delta_err = draw_prediction_overlay(
            ax,
            rgb,
            gt,
            predictions.get(variant),
            true_errors,
        )
        if predictions.get(variant) is None:
            pred_text = "prediction skipped"
        elif mean_err is None:
            pred_text = "no matched pose"
        elif delta_err is None:
            pred_text = f"mean KPT err={mean_err:.2f}px"
        else:
            pred_text = f"mean KPT err={mean_err:.2f}px  ΔTrue={delta_err:+.2f}px"
        ax.text(
            0.02,
            0.02,
            pred_text,
            transform=ax.transAxes,
            fontsize=7,
            color="white",
            va="bottom",
            bbox=dict(facecolor="black", alpha=0.6, pad=2),
        )

    axes[0, 0].set_ylabel("Absolute Depth\n(model input)", fontsize=9)
    axes[1, 0].set_ylabel("Structure view\n(VIS ONLY)", fontsize=9)
    axes[2, 0].set_ylabel("|Variant - True|", fontsize=9)
    axes[3, 0].set_ylabel("RGB + GT / prediction", fontsize=9)
    group_title = GROUPS[group_name]["title"]
    fig.suptitle(f"{image_name}   |   {group_title}", fontsize=13, weight="bold")
    fig.tight_layout(rect=(0, 0, 1, 0.965))
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=150, bbox_inches="tight")
    plt.close(fig)


def plot_summary_metrics(results: dict[str, Any], order: list[str], output_path: Path) -> None:
    usable = [v for v in order if v in results]
    if not usable:
        return
    pose = [results[v]["pose_map"] for v in usable]
    box = [results[v]["box_map"] for v in usable]
    y = np.arange(len(usable))
    height = max(5.0, 0.36 * len(usable) + 2.0)
    fig, ax = plt.subplots(figsize=(10.5, height))
    ax.barh(y - 0.18, box, height=0.34, label="Box mAP50-95")
    ax.barh(y + 0.18, pose, height=0.34, label="Pose mAP50-95")
    ax.set_yticks(y, [VARIANT_LABELS.get(v, v) for v in usable], fontsize=8)
    ax.invert_yaxis()
    ax.set_xlabel("mAP50-95")
    ax.set_xlim(0.0, 1.0)
    ax.grid(axis="x", alpha=0.2)
    ax.legend()
    ax.set_title("Depth ablation metrics overview")
    fig.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=160, bbox_inches="tight")
    plt.close(fig)


def infer_constant_value(ablation_root: Path, variant: str) -> int | None:
    img_dir = variant_image_dir(ablation_root, variant)
    paths = sorted(p for p in img_dir.glob("*") if p.suffix.lower() in {".png", ".jpg", ".jpeg"})
    if not paths:
        return None
    depth = read_rgba(paths[0])[:, :, 3]
    if variant.startswith("fixed_valid_depth"):
        values = np.unique(depth[depth > 0])
    else:
        values = np.unique(depth)
    if len(values) == 1:
        return int(values[0])
    return None


def plot_sweep(
    output_path: Path,
    title: str,
    points: list[tuple[float, str]],
    results: dict[str, Any],
    x_label: str,
) -> None:
    usable = [(x, v) for x, v in points if v in results]
    if len(usable) < 2:
        return
    xs = [x for x, _ in usable]
    box = [results[v]["box_map"] for _, v in usable]
    pose = [results[v]["pose_map"] for _, v in usable]
    fig, ax = plt.subplots(figsize=(8.5, 5.2))
    ax.plot(xs, box, marker="o", label="Box mAP50-95")
    ax.plot(xs, pose, marker="o", label="Pose mAP50-95")
    for x, yv in zip(xs, pose):
        ax.annotate(f"{yv:.4f}", (x, yv), textcoords="offset points", xytext=(0, 7), ha="center", fontsize=8)
    ax.set_xlabel(x_label)
    ax.set_ylabel("mAP50-95")
    ax.set_title(title)
    ax.grid(alpha=0.25)
    ax.legend()
    fig.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=160, bbox_inches="tight")
    plt.close(fig)


def plot_keypoint_delta_heatmap(
    error_rows: list[dict[str, Any]],
    variants: list[str],
    output_path: Path,
) -> None:
    rows = [r for r in error_rows if r.get("delta_vs_true_px") is not None]
    if not rows:
        return
    kpt_ids = sorted({int(r["keypoint"]) for r in rows})
    usable_variants = [v for v in variants if any(r["variant"] == v for r in rows)]
    if not usable_variants or not kpt_ids:
        return

    matrix = np.full((len(usable_variants), len(kpt_ids)), np.nan, dtype=np.float32)
    for row_idx, variant in enumerate(usable_variants):
        for col_idx, kpt in enumerate(kpt_ids):
            vals = [
                float(r["delta_vs_true_px"])
                for r in rows
                if r["variant"] == variant and int(r["keypoint"]) == kpt
            ]
            if vals:
                matrix[row_idx, col_idx] = float(np.mean(vals))

    finite = matrix[np.isfinite(matrix)]
    if finite.size == 0:
        return
    vmax = max(1.0, float(np.max(np.abs(finite))))
    fig_h = max(5.0, 0.34 * len(usable_variants) + 2.2)
    fig, ax = plt.subplots(figsize=(9.0, fig_h))
    im = ax.imshow(matrix, cmap="coolwarm", vmin=-vmax, vmax=vmax, aspect="auto")
    ax.set_xticks(np.arange(len(kpt_ids)), [f"K{k}" for k in kpt_ids])
    ax.set_yticks(
        np.arange(len(usable_variants)),
        [VARIANT_LABELS.get(v, v) for v in usable_variants],
        fontsize=8,
    )
    ax.set_title("Mean per-keypoint error change vs True Depth")
    ax.set_xlabel("Keypoint")
    ax.set_ylabel("Variant")
    for i in range(matrix.shape[0]):
        for j in range(matrix.shape[1]):
            if np.isfinite(matrix[i, j]):
                ax.text(j, i, f"{matrix[i, j]:+.1f}", ha="center", va="center", fontsize=7)
    fig.colorbar(im, ax=ax, label="Δ error vs True (px); positive = worse")
    fig.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=160, bbox_inches="tight")
    plt.close(fig)


