# --------------------------------------------------------------------------- main analysis

def main() -> None:
    args = parse_args()
    args.ablation_root = args.ablation_root.resolve()
    args.weights = args.weights.resolve()
    if args.scale25_weights is not None:
        args.scale25_weights = args.scale25_weights.resolve()
    out_dir = (args.out if args.out is not None else args.ablation_root / "report").resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    print("=" * 72)
    print("RGBD Depth ablation visualization")
    print(f"ablation root : {args.ablation_root}")
    print(f"raw weights   : {args.weights}")
    print(f"scale25 model : {args.scale25_weights or '-'}")
    print(f"report out    : {out_dir}")
    print(f"groups        : {args.groups}")
    print("=" * 72)

    if not args.ablation_root.exists():
        raise FileNotFoundError(
            f"Ablation root does not exist: {args.ablation_root}\n"
            "Run ablate_rgbd_depth.py first to generate the controlled test variants."
        )

    available = available_variants(args.ablation_root)
    if "true_depth" not in available:
        raise FileNotFoundError(
            f"Missing true_depth data under {args.ablation_root}. Run ablate_rgbd_depth.py first."
        )

    selected_variants: list[str] = []
    for group_name in args.groups:
        for variant in GROUPS[group_name]["variants"]:
            if variant in available and variant not in selected_variants:
                selected_variants.append(variant)
    if "true_depth" not in selected_variants:
        selected_variants.insert(0, "true_depth")

    image_names = image_names_for_variants(args.ablation_root, selected_variants)
    if args.max_images > 0:
        image_names = image_names[: args.max_images]
    if not image_names:
        raise RuntimeError("No common test images found across selected variants.")

    print(f"[data] available variants = {len(available)}")
    print(f"[data] selected variants  = {len(selected_variants)}")
    print(f"[data] common test images = {len(image_names)}")

    ablation_result = read_json(args.ablation_root / "ablation_result.json") or {}
    results: dict[str, Any] = ablation_result.get("results", {})
    result_order = [v for v in ablation_result.get("selected", selected_variants) if v in results]
    if not result_order:
        result_order = [v for v in selected_variants if v in results]

    if results:
        write_summary_metrics_csv(results, result_order, out_dir / "summary_metrics.csv")

    model = None
    YOLO = None
    if not args.skip_predict:
        if not args.weights.exists():
            raise FileNotFoundError(f"Raw RGBD weights not found: {args.weights}")
        YOLO = load_yolo_class()
        model = YOLO(str(args.weights), task="pose")

    predictions_json: dict[str, Any] = {}
    error_rows: list[dict[str, Any]] = []
    group_outputs: dict[str, list[Path]] = {name: [] for name in args.groups}

    for image_idx, image_name in enumerate(image_names, start=1):
        print(f"[{image_idx:02d}/{len(image_names):02d}] {image_name}")
        images: dict[str, np.ndarray] = {}
        preds: dict[str, dict[str, Any] | None] = {}
        for variant in selected_variants:
            image_path = variant_image_dir(args.ablation_root, variant) / image_name
            images[variant] = read_rgba(image_path)

        height, width = images["true_depth"].shape[:2]
        label_path = variant_label_dir(args.ablation_root, "true_depth") / (Path(image_name).stem + ".txt")
        gt = load_ground_truth(label_path, width, height)
        if gt is not None and gt.get("label_count", 1) != 1:
            print(f"  [warning] {image_name}: label_count={gt['label_count']}; visualizer uses first label")

        if model is not None:
            for variant in selected_variants:
                preds[variant] = predict_one(model, images[variant], args.imgsz, args.conf, args.device)
        else:
            preds = {variant: None for variant in selected_variants}

        true_errors = keypoint_errors(gt, preds.get("true_depth")) if preds.get("true_depth") else None
        true_depth = images["true_depth"][:, :, 3]

        predictions_json[image_name] = {
            "ground_truth": None
            if gt is None
            else {
                "box": np.asarray(gt["box"]).tolist(),
                "keypoints": np.asarray(gt["keypoints"]).tolist(),
            },
            "variants": {variant: prediction_to_jsonable(preds.get(variant)) for variant in selected_variants},
        }

        for variant in selected_variants:
            depth = images[variant][:, :, 3]
            valid = depth > 0
            true_valid = true_depth > 0
            depth_mae = (
                float(np.mean(np.abs(depth.astype(np.float32) - true_depth.astype(np.float32))[true_valid]))
                if np.any(true_valid)
                else 0.0
            )
            pred = preds.get(variant)
            errs = keypoint_errors(gt, pred) if pred is not None else None
            iou = box_iou(gt["box"], pred["box"]) if gt is not None and pred is not None else None
            pred_kpts = None if pred is None else pred.get("keypoints")
            n_kpts = 0 if gt is None else len(gt["keypoints"])
            for kpt_idx in range(n_kpts):
                err = None
                if errs is not None and kpt_idx < len(errs) and np.isfinite(errs[kpt_idx]):
                    err = float(errs[kpt_idx])
                true_err = None
                if true_errors is not None and kpt_idx < len(true_errors) and np.isfinite(true_errors[kpt_idx]):
                    true_err = float(true_errors[kpt_idx])
                pred_conf = None
                if pred_kpts is not None and kpt_idx < len(pred_kpts):
                    pred_conf = float(pred_kpts[kpt_idx][2])
                error_rows.append(
                    {
                        "image": image_name,
                        "variant": variant,
                        "variant_label": VARIANT_LABELS.get(variant, variant),
                        "keypoint": kpt_idx,
                        "error_px": err,
                        "true_error_px": true_err,
                        "delta_vs_true_px": None if err is None or true_err is None else err - true_err,
                        "pred_kpt_conf": pred_conf,
                        "box_iou": iou,
                        "box_conf": None if pred is None else pred.get("box_conf"),
                        "depth_min": int(depth.min()),
                        "depth_max": int(depth.max()),
                        "depth_mean_all": float(depth.mean()),
                        "depth_mean_valid": float(depth[valid].mean()) if np.any(valid) else 0.0,
                        "depth_std_valid": float(depth[valid].std()) if np.any(valid) else 0.0,
                        "depth_mae_valid_vs_true": depth_mae,
                    }
                )

        for group_name in args.groups:
            group_variants = [v for v in GROUPS[group_name]["variants"] if v in selected_variants]
            if not group_variants:
                continue
            output_path = out_dir / "groups" / group_name / f"{Path(image_name).stem}.png"
            plot_group_figure(
                output_path,
                image_name,
                group_name,
                group_variants,
                images,
                gt,
                preds,
            )
            group_outputs[group_name].append(output_path)

    (out_dir / "predictions.json").write_text(
        json.dumps(predictions_json, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    write_keypoint_csv(error_rows, out_dir / "keypoint_errors.csv")

    summary_dir = out_dir / "summary"
    summary_images: list[Path] = []
    if results:
        metrics_path = summary_dir / "metrics_overview.png"
        plot_summary_metrics(results, result_order, metrics_path)
        if metrics_path.exists():
            summary_images.append(metrics_path)

        constant_points: list[tuple[float, str]] = []
        for variant in GROUPS["constant_sweep"]["variants"]:
            if variant == "zero_depth":
                value = 0
            else:
                value = infer_constant_value(args.ablation_root, variant)
            if value is not None:
                constant_points.append((float(value), variant))
        constant_points.sort(key=lambda item: item[0])
        path = summary_dir / "constant_sweep.png"
        plot_sweep(path, "Full Constant Sweep", constant_points, results, "Full-image constant Depth value")
        if path.exists():
            summary_images.append(path)

        fixed_points: list[tuple[float, str]] = []
        for variant in GROUPS["fixed_valid_sweep"]["variants"]:
            if variant == "zero_depth":
                value = 0
            else:
                value = infer_constant_value(args.ablation_root, variant)
            if value is not None:
                fixed_points.append((float(value), variant))
        fixed_points.sort(key=lambda item: item[0])
        path = summary_dir / "fixed_valid_sweep.png"
        plot_sweep(path, "Fixed Valid Sweep", fixed_points, results, "Constant value inside valid mask")
        if path.exists():
            summary_images.append(path)

        scale_points = [
            (0.0, "zero_depth"),
            (25.0, "scaled_true_depth_25"),
            (50.0, "scaled_true_depth_50"),
            (75.0, "scaled_true_depth_75"),
            (100.0, "true_depth"),
        ]
        path = summary_dir / "true_depth_scale_sweep.png"
        plot_sweep(path, "True Depth Scale Sweep", scale_points, results, "Depth amplitude scale (%)")
        if path.exists():
            summary_images.append(path)

    if not args.skip_predict:
        heatmap_path = summary_dir / "keypoint_delta_heatmap.png"
        plot_keypoint_delta_heatmap(error_rows, result_order or selected_variants, heatmap_path)
        if heatmap_path.exists():
            summary_images.append(heatmap_path)

    cross_scale: dict[str, Any] | None = None
    if args.scale25_weights is not None:
        if args.skip_predict:
            print("[cross-scale] skipped because --skip-predict was requested")
        elif not args.scale25_weights.exists():
            raise FileNotFoundError(f"Scale25 weights not found: {args.scale25_weights}")
        elif "scaled_true_depth_25" not in available:
            print("[cross-scale] skipped: scaled_true_depth_25 variant is missing")
        elif YOLO is None:
            raise RuntimeError("Internal error: YOLO class not loaded")
        else:
            print("[cross-scale] evaluating Scale25-trained model on Raw and Scale25 test encodings...")
            scale_model = YOLO(str(args.scale25_weights), task="pose")
            raw_yaml = variant_yaml_path(args.ablation_root, "true_depth")
            scale_yaml = variant_yaml_path(args.ablation_root, "scaled_true_depth_25")
            if not raw_yaml.exists() or not scale_yaml.exists():
                raise FileNotFoundError("Cross-scale YAML missing; rerun ablate_rgbd_depth.py to generate variants")

            raw_true_metrics = results.get("true_depth")
            raw_scale_metrics = results.get("scaled_true_depth_25")
            if raw_true_metrics is None or raw_scale_metrics is None:
                print("[cross-scale] raw-trained metrics missing from ablation_result.json; evaluating them now")
                raw_model_for_val = YOLO(str(args.weights), task="pose")
                raw_true_metrics = evaluate_model_on_variant(
                    raw_model_for_val,
                    raw_yaml,
                    args.imgsz,
                    args.batch,
                    args.device,
                    out_dir / "_val_runs",
                    "raw_trained_raw_test",
                )
                raw_scale_metrics = evaluate_model_on_variant(
                    raw_model_for_val,
                    scale_yaml,
                    args.imgsz,
                    args.batch,
                    args.device,
                    out_dir / "_val_runs",
                    "raw_trained_scale25_test",
                )

            scale_raw_metrics = evaluate_model_on_variant(
                scale_model,
                raw_yaml,
                args.imgsz,
                args.batch,
                args.device,
                out_dir / "_val_runs",
                "scale25_trained_raw_test",
            )
            scale_scale_metrics = evaluate_model_on_variant(
                scale_model,
                scale_yaml,
                args.imgsz,
                args.batch,
                args.device,
                out_dir / "_val_runs",
                "scale25_trained_scale25_test",
            )

            cross_scale = {
                "raw_trained_raw": {
                    "box_map": float(raw_true_metrics["box_map"]),
                    "pose_map": float(raw_true_metrics["pose_map"]),
                },
                "raw_trained_scale25": {
                    "box_map": float(raw_scale_metrics["box_map"]),
                    "pose_map": float(raw_scale_metrics["pose_map"]),
                },
                "scale25_trained_raw": scale_raw_metrics,
                "scale25_trained_scale25": scale_scale_metrics,
            }

            cross_dir = out_dir / "cross_scale"
            box_matrix = np.asarray(
                [
                    [cross_scale["raw_trained_raw"]["box_map"], cross_scale["raw_trained_scale25"]["box_map"]],
                    [cross_scale["scale25_trained_raw"]["box_map"], cross_scale["scale25_trained_scale25"]["box_map"]],
                ],
                dtype=np.float32,
            )
            pose_matrix = np.asarray(
                [
                    [cross_scale["raw_trained_raw"]["pose_map"], cross_scale["raw_trained_scale25"]["pose_map"]],
                    [cross_scale["scale25_trained_raw"]["pose_map"], cross_scale["scale25_trained_scale25"]["pose_map"]],
                ],
                dtype=np.float32,
            )
            box_heatmap = cross_dir / "cross_scale_box_map.png"
            pose_heatmap = cross_dir / "cross_scale_pose_map.png"
            plot_cross_scale_heatmap(box_matrix, "Cross-scale Box mAP50-95", box_heatmap)
            plot_cross_scale_heatmap(pose_matrix, "Cross-scale Pose mAP50-95", pose_heatmap)
            cross_scale["box_heatmap"] = box_heatmap
            cross_scale["pose_heatmap"] = pose_heatmap

            cross_image_paths: list[Path] = []
            # Reuse the raw-model predictions already computed above and run only Scale25 model here.
            for image_name in image_names:
                raw_image = read_rgba(variant_image_dir(args.ablation_root, "true_depth") / image_name)
                scale_image = read_rgba(variant_image_dir(args.ablation_root, "scaled_true_depth_25") / image_name)
                h, w = raw_image.shape[:2]
                gt = load_ground_truth(
                    variant_label_dir(args.ablation_root, "true_depth") / (Path(image_name).stem + ".txt"),
                    w,
                    h,
                )
                raw_raw_pred = predictions_json[image_name]["variants"].get("true_depth")
                raw_scale_pred = predictions_json[image_name]["variants"].get("scaled_true_depth_25")
                # Convert JSONable records back to ndarray-friendly prediction dictionaries.
                def _restore(record):
                    if record is None:
                        return None
                    return {
                        "box": None if record["box"] is None else np.asarray(record["box"], dtype=np.float32),
                        "box_conf": record.get("box_conf"),
                        "keypoints": None
                        if record["keypoints"] is None
                        else np.asarray(record["keypoints"], dtype=np.float32),
                    }

                raw_raw_pred = _restore(raw_raw_pred)
                raw_scale_pred = _restore(raw_scale_pred)
                scale_raw_pred = predict_one(scale_model, raw_image, args.imgsz, args.conf, args.device)
                scale_scale_pred = predict_one(scale_model, scale_image, args.imgsz, args.conf, args.device)
                image_path = cross_dir / "images" / f"{Path(image_name).stem}.png"
                plot_cross_scale_image(
                    image_path,
                    image_name,
                    raw_image,
                    scale_image,
                    gt,
                    raw_raw_pred,
                    raw_scale_pred,
                    scale_raw_pred,
                    scale_scale_pred,
                )
                cross_image_paths.append(image_path)
            cross_scale["images"] = cross_image_paths

            with (cross_dir / "cross_scale_metrics.csv").open("w", newline="", encoding="utf-8-sig") as f:
                writer = csv.writer(f)
                writer.writerow(["train_encoding", "test_encoding", "box_map", "pose_map"])
                writer.writerow(["Raw", "Raw", cross_scale["raw_trained_raw"]["box_map"], cross_scale["raw_trained_raw"]["pose_map"]])
                writer.writerow(["Raw", "Scale25", cross_scale["raw_trained_scale25"]["box_map"], cross_scale["raw_trained_scale25"]["pose_map"]])
                writer.writerow(["Scale25", "Raw", cross_scale["scale25_trained_raw"]["box_map"], cross_scale["scale25_trained_raw"]["pose_map"]])
                writer.writerow(["Scale25", "Scale25", cross_scale["scale25_trained_scale25"]["box_map"], cross_scale["scale25_trained_scale25"]["pose_map"]])

    build_html_report(out_dir, args, results, group_outputs, summary_images, cross_scale)

    print("\n" + "=" * 72)
    print("Visualization complete")
    print(f"HTML report          : {out_dir / 'index.html'}")
    print(f"Keypoint error table : {out_dir / 'keypoint_errors.csv'}")
    print(f"Predictions          : {out_dir / 'predictions.json'}")
    if results:
        print(f"Metric table         : {out_dir / 'summary_metrics.csv'}")
    print("=" * 72)


if __name__ == "__main__":
    main()
