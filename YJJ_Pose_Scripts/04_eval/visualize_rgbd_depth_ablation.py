def prediction_to_jsonable(pred: dict[str, Any] | None) -> dict[str, Any] | None:
    if pred is None:
        return None
    return {
        "box": None if pred.get("box") is None else np.asarray(pred["box"]).tolist(),
        "box_conf": pred.get("box_conf"),
        "keypoints": None if pred.get("keypoints") is None else np.asarray(pred["keypoints"]).tolist(),
    }


def write_keypoint_csv(rows: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fields = [
        "image",
        "variant",
        "variant_label",
        "keypoint",
        "error_px",
        "true_error_px",
        "delta_vs_true_px",
        "pred_kpt_conf",
        "box_iou",
        "box_conf",
        "depth_min",
        "depth_max",
        "depth_mean_all",
        "depth_mean_valid",
        "depth_std_valid",
        "depth_mae_valid_vs_true",
    ]
    with path.open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        for row in rows:
            writer.writerow({key: row.get(key) for key in fields})


def write_summary_metrics_csv(results: dict[str, Any], order: list[str], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    metric_keys = [
        "box_p",
        "box_r",
        "box_map50",
        "box_map",
        "pose_p",
        "pose_r",
        "pose_map50",
        "pose_map",
    ]
    with path.open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f)
        writer.writerow(["variant", "label", *metric_keys])
        for variant in order:
            if variant not in results:
                continue
            writer.writerow(
                [variant, VARIANT_LABELS.get(variant, variant)]
                + [results[variant].get(key) for key in metric_keys]
            )


